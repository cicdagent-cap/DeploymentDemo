#!/usr/bin/env bash
set -euo pipefail
# Capability-aware GitHub Actions workflow generation (structural, not comments-only).

REPO=""
REQUEST=""
SCOPE_FILE="${CICD_APPROVED_SCOPE_FILE:-}"
DRY_RUN=0
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=/dev/null
source "$SCRIPT_DIR/lib_kit_paths.sh"
KIT_ROOT="$CICD_KIT_HOME"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --repo) REPO="${2:-}"; shift 2 ;;
    --request) REQUEST="${2:-}"; shift 2 ;;
    --scope-file) SCOPE_FILE="${2:-}"; shift 2 ;;
    --dry-run) DRY_RUN=1; shift ;;
    *) echo "Unknown: $1" >&2; exit 1 ;;
  esac
done

[[ -n "$REPO" && -n "$REQUEST" ]] || { echo "Usage: generate_pipeline.sh --repo <path> --request <file> --scope-file <scope> [--dry-run]"; exit 1; }
REPO="$(cd "$REPO" && pwd)"
TEMPLATES_DIR="$(cicd_find_templates_dir "$REPO")" || { echo "templates dir unresolved from installed/source layout" >&2; exit 1; }

OUT_REL="$(ruby -ryaml -e 'd=YAML.safe_load(File.read(ARGV[0]), aliases:true)||{}; puts d.dig("pipeline","output_file")' "$REQUEST")"
ENV_NAME="$(ruby -ryaml -e 'd=YAML.safe_load(File.read(ARGV[0]), aliases:true)||{}; puts d["environment"]||""' "$REQUEST")"
DEST_NAME="$(ruby -ryaml -e 'd=YAML.safe_load(File.read(ARGV[0]), aliases:true)||{}; puts d["destination"]||"artifacts-only"' "$REQUEST")"

if [[ "$DRY_RUN" -eq 0 ]]; then
  "$KIT_ROOT/harness/require_approval.sh" --action generate_pipeline --repo "$REPO" \
    --scope-file "${SCOPE_FILE:?scope required}" --path "$OUT_REL" \
    --environment "$ENV_NAME" --destination "$DEST_NAME"
fi

"$(cicd_script validate_request.sh)" --request "$REQUEST" --repo "$REPO" >/tmp/cicd-gen-val.json
DET="$("$(cicd_script detect_project_platform.sh)" --repo "$REPO" --format json)"
REC="$("$(cicd_script recommend_pipeline_action.sh)" --repo "$REPO" --request "$REQUEST")"

python3 - "$KIT_ROOT" "$REPO" "$REQUEST" "$DET" "$REC" "$DRY_RUN" "$TEMPLATES_DIR" <<'PY'
import json, sys, subprocess
from pathlib import Path

kit, repo, req_path, det_raw, rec_raw, dry, templates_dir = sys.argv[1:8]
dry = dry == "1"
req = json.loads(subprocess.check_output(
    ["ruby","-ryaml","-rjson","-e","print JSON.generate(YAML.safe_load(STDIN.read, aliases:true)||{})"],
    input=Path(req_path).read_bytes()))
det = json.loads(det_raw)
rec = json.loads(rec_raw)

if rec.get("action") == "reuse":
    print(json.dumps({"status": "reuse", "message": "Existing pipeline recommended; no file written", "recommendation": rec}, indent=2))
    sys.exit(0)

caps = set(req.get("capabilities") or [])
provider = req.get("provider") or "github_actions"
if provider != "github_actions":
    print("provider is not github_actions; use generate_jenkins_pipeline.sh", file=sys.stderr)
    sys.exit(1)

dest = req.get("destination") or "artifacts-only"
dist_caps = {"testflight", "firebase_app_distribution", "google_play_tracks", "ios_archive_ipa"}
wants_dist = bool(caps & dist_caps) or dest in ("testflight", "firebase_app_distribution", "google_play")
wants_notify = bool((req.get("notifications") or {}).get("enabled")) or "notifications_teams_slack" in caps
wants_tests = "unit_tests" in caps
ga = req.get("github_actions") or {}

if ga.get("template") == "entry-reusable":
    template_name = "entry-reusable-workflow.template.yml"
elif not wants_dist and dest in ("artifacts-only", "none", None):
    template_name = "mobile-ci-build-test.template.yml"
else:
    template_name = "mobile-ci-workflow.template.yml"

tmpl = Path(templates_dir) / template_name
if not tmpl.is_file():
    print(f"template not found: {tmpl}", file=sys.stderr)
    sys.exit(1)
text = tmpl.read_text()

runner = req.get("runner_label") or ga.get("runner_label") or det.get("runner") or "macos-latest"
branch = ga.get("default_branch") or "main"
project = det.get("project_file") or "__DEFAULT_PROJECT_FILE__"
scheme = det.get("default_scheme") or "__DEFAULT_SCHEME__"
name = (req.get("pipeline") or {}).get("name") or "CI_Pipeline"
out_rel = (req.get("pipeline") or {}).get("output_file")
env_name = req.get("environment") or ""

header = f"""# Generated by cicd-agent-kit generate_pipeline.sh
# template: {template_name}
# capabilities: {sorted(caps)}
# environment: {env_name}
# destination: {dest}
# distribution_enabled: {str(wants_dist).lower()}
# notifications_enabled: {str(wants_notify).lower()}
# unit_tests: {str(wants_tests).lower()}
# structural_guarantee: build-test template embeds CICD_ALLOW_DISTRIBUTION=false and omits notify/upload jobs
"""

repl = {
    "__PIPELINE_NAME__": name,
    "__RUNNER_LABEL__": runner,
    "__DEFAULT_BRANCH__": branch,
    "__DEFAULT_PROJECT_FILE__": project,
    "__DEFAULT_SCHEME__": scheme,
    "__ENABLE_UNIT_TESTS__": "true" if wants_tests else "false",
}
for k, v in repl.items():
    text = text.replace(k, str(v))

if template_name == "mobile-ci-workflow.template.yml":
    if not wants_notify:
        text = text.replace("vars.CICD_NOTIFICATIONS_ENABLED == 'true'", "false")
        text = text.replace("inputs.enable_notifications == true", "false")
    extra_env = """
env:
  CICD_UPLOAD_TESTFLIGHT: {tf}
  CICD_DISTRIBUTE_FIREBASE: {fb}
  CICD_DISTRIBUTE_GOOGLE_PLAY: {gp}
  CICD_USE_MATCH: {match}
  CICD_ALLOW_DISTRIBUTION: {allow}
""".format(
        tf="true" if "testflight" in caps and dest == "testflight" else "false",
        fb="true" if "firebase_app_distribution" in caps and dest == "firebase_app_distribution" else "false",
        gp="true" if "google_play_tracks" in caps and dest == "google_play" else "false",
        match="true" if ((req.get("signing") or {}).get("strategy") == "match") else "false",
        allow="true" if wants_dist else "false",
    )
    if "\nenv:\n" not in text:
        text = text.replace("permissions:\n  contents: read\n", "permissions:\n  contents: read\n" + extra_env)
    # Strip release upload step when distribution not requested: force build lane only
    if not wants_dist:
        text = text.replace('MODE="${{ steps.mode.outputs.mode }}"', 'MODE="build"')
        text = text.replace("bundle exec fastlane ${{ steps.lanes.outputs.lane }}", "bundle exec fastlane ios build || bundle exec fastlane android build")

out_path = Path(repo) / out_rel
content = header + text
result = {
    "status": "dry_run" if dry else "written",
    "template": template_name,
    "workflow_path": out_rel,
    "capabilities": sorted(caps),
    "destination": dest,
    "environment": env_name,
    "runner": runner,
    "distribution_enabled": wants_dist,
    "notifications_enabled": wants_notify,
    "unit_tests": wants_tests,
    "structural_no_upload": template_name == "mobile-ci-build-test.template.yml",
}
if dry:
    result["would_write"] = str(out_path)
    result["bytes"] = len(content)
    # Prove capability changed template selection
    result["content_markers"] = {
        "has_allow_distribution_false": "CICD_ALLOW_DISTRIBUTION: \"false\"" in content or "CICD_ALLOW_DISTRIBUTION: false" in content,
        "has_notify_job": "notify-triggered:" in content,
        "has_testflight_env_true": "CICD_UPLOAD_TESTFLIGHT: true" in content or 'CICD_UPLOAD_TESTFLIGHT: "true"' in content,
    }
    print(json.dumps(result, indent=2))
    sys.exit(0)

out_path.parent.mkdir(parents=True, exist_ok=True)
out_path.write_text(content)
print(json.dumps(result, indent=2))
PY
